"""Case continuation insights: "what happens next".

Two parts, kept apart on purpose:

1. FROM THE JUDGMENT. The model reads the judgment and reports how the case was
   disposed of, what the court ordered, any time limits or dates it set, and what
   is to happen next in the case itself. Every point must cite pages and give a
   word-for-word quote, and the server checks it against the judgment exactly as
   it does for the summary.

2. GENERAL INFORMATION. Routes people commonly consider after a judgment (review,
   appeal and so on) are NOT generated by the model. They come from the fixed,
   hand-written table below, chosen by the level of the court. They carry no
   deadlines, because those depend on the type of case and change with the law,
   and they are labelled as general information, not advice. Nothing here predicts
   what any court would do.
"""
