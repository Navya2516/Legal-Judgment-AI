# ------------------------------------------------------------ court level

_HEADER_CHARS = 800  # the court's name is near the top of the first page

_SC_ANYWHERE = [  # strong signs of a Supreme Court judgment, on either of the first two pages
    re.compile(r"in\s+the\s+supreme\s+court", re.I),
    re.compile(r"supreme\s+court\s+reports", re.I),
    re.compile(r"\[\s*\d{4}\s*\]\s*\d+\s*S\.?\s?C\.?\s?R\.?", re.I),  # [2017] 10 S.C.R.
    re.compile(r"\bCJI\b"),
]
_SC_HEADER = re.compile(r"supreme\s+court\s+of\s+india", re.I)
_HC_HEADER = re.compile(r"\bhigh\s+court\b", re.I)
_TRIAL_HEADER = re.compile(
    r"\b(?:district\s+(?:court|judge)|sessions\s+(?:court|judge)|city\s+civil\s+court|civil\s+judge|"
    r"metropolitan\s+magistrate|judicial\s+magistrate|chief\s+judicial\s+magistrate|family\s+court)\b",
    re.I,
)
_TRIBUNAL_HEADER = re.compile(r"\b(?:tribunal|commission)\b", re.I)


def detect_court_level(pages: list[PageText]) -> tuple[str, str]:
    """Guess the court level from the opening of the judgment. Returns (level, how)."""
    opening = [p for p in sorted(pages, key=lambda p: p.page_number) if p.text.strip()][:2]
    if not opening:
        return "unknown", "The judgment has no text to read."
    first = opening[0]

    def found(rx: re.Pattern, page: PageText, limit: Optional[int] = None) -> Optional[str]:
        text = page.text[:limit] if limit else page.text
        match = rx.search(text)
        return f'Found "{" ".join(match.group(0).split())}" on page {page.page_number}.' if match else None

    for page in opening:
        for rx in _SC_ANYWHERE:
            hit = found(rx, page)
            if hit:
                return "supreme_court", hit
    hit = found(_SC_HEADER, first, _HEADER_CHARS)
    if hit:
        return "supreme_court", hit
    for level, rx in (("high_court", _HC_HEADER), ("trial_court", _TRIAL_HEADER), ("tribunal", _TRIBUNAL_HEADER)):
        hit = found(rx, first, _HEADER_CHARS)
        if hit:
            return level, hit
    return "unknown", "No court name was recognised at the top of the first page."


