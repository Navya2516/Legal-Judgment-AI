def avenues_for(level: str) -> list[Avenue]:
    routes = list(AVENUES.get(level, AVENUES["unknown"]))
    if level == "supreme_court":
        routes.insert(0, FINALITY_NOTE_SC)
    return [a.model_copy() for a in routes]


# ----------------------------------------------------------------- the model

CONTINUATION_QUERIES = [
    "the final order and the directions given by the court",
    "the matter is remanded, sent back, or placed before a bench for further hearing",
    "liberty to approach the court again or to file fresh proceedings",
    "costs awarded and the time allowed for compliance with the directions",
    "the petition, appeal or reference is allowed, dismissed or disposed of",
    "interim orders, stay or bail continued, vacated or made absolute",
]
PER_ASPECT = 8

CONTINUATION_TASK = """CONTINUATION_TASK
Say what the judgment below itself says about how the case ended and what happens next in the case.
Report ONLY what the judgment states. Do not describe appeals, review or other routes that the judgment does not mention, and do not predict anything.
Return JSON with exactly these keys:
{
  "disposition": {"label": one of "allowed" | "partly_allowed" | "dismissed" | "disposed_of" | "remanded" | "reference_answered" | "other",
                  "text": "one plain sentence on how the court disposed of the case",
                  "pages": [page numbers], "quote": "exact words from the judgment"}   // or null if the text does not say
  "directions": [point],           // what the court ordered and who must do what, including costs
  "deadlines": [point],            // time limits or dates the court set, written exactly as the judgment gives them
  "further_proceedings": [point]   // what is to happen next in the case itself: matters sent back, listed before another bench, liberty to approach, questions left open
}
where each point is {"text": string, "pages": [page numbers], "quote": "exact words from the judgment"}.
Copy numbers exactly as the judgment writes them (if it writes "four weeks", write "four weeks"). Use an empty list when the judgment has nothing for a key.

<judgment_text>
%s
</judgment_text>"""

_NUMBER = re.compile(r"\d+(?:\.\d+)?")


def _numbers(text: str) -> set[str]:
    return set(_NUMBER.findall(re.sub(r"(?<=\d),(?=\d{2,3}\b)", "", text)))


def _ground(
    raw: list[RawPoint], texts: PageTexts, cleaned: dict[int, str], allowed: set[int], strict: bool
) -> tuple[list[Point], int, int, int]:
    """Check each point; a verified point whose digits are not on its pages is demoted to cited."""
    kept: list[Point] = []
    verified = cited = dropped = 0
    for item in raw:
        result = check_claim(item.pages, item.quote, texts, allowed)
        status = result.status
        if status == VERIFIED:
            on_pages = set().union(*(_numbers(cleaned.get(p, "")) for p in result.pages))
            if not _numbers(item.text) <= on_pages:
                status = "cited"  # the sentence mentions a figure that is not on the cited page
        if status == UNSUPPORTED or (strict and status != VERIFIED):
            dropped += 1
            continue
        verified += status == VERIFIED
        cited += status != VERIFIED
        kept.append(Point(text=item.text.strip(), pages=result.pages, status=status, quote=result.quote))  # type: ignore[arg-type]
    return kept, verified, cited, dropped


def generate_continuation(
    doc_id: str,
    *,
    pages: list[PageText],
    settings: Settings,
    index_store: IndexStore,
    get_embedder: Callable[[], Embedder],
    llm: LlmClient,
    court_level: Optional[str] = None,
) -> ContinuationResult:
    cleaned = clean_pages(pages)
    if court_level:
        level, basis = court_level, "Set by you."
    else:
        level, basis = detect_court_level(pages)
    context: Context = build_context(
        doc_id,
        cleaned,
        settings,
        index_store,
        get_embedder,
        aspects=CONTINUATION_QUERIES,
        per_aspect=PER_ASPECT,
        purpose="analysis",
        focus="the final order, directions, costs and what happens next",
    )
    if not context.pages:
        raise LlmError("bad_output", "The document has no text to analyse.")

    raw = generate_validated(
        llm, system=SYSTEM_PROMPT, prompt=CONTINUATION_TASK % context.text, model=RawContinuation
    )
    texts = PageTexts(cleaned)
    strict = settings.llm_drop_unverified

    sections: dict[str, list[Point]] = {}
    verified = cited = dropped = 0
    total = 0
    for name in ("directions", "deadlines", "further_proceedings"):
        items = getattr(raw, name)
        total += len(items)
        points, v, c, d = _ground(items, texts, cleaned, context.pages, strict)
        sections[name] = points
        verified, cited, dropped = verified + v, cited + c, dropped + d

    disposition: Optional[Disposition] = None
    if raw.disposition is not None:
        total += 1
        d = raw.disposition
        grounded, v, c, dr = _ground(
            [RawPoint(text=d.text, pages=d.pages, quote=d.quote)], texts, cleaned, context.pages, strict
        )
        verified, cited, dropped = verified + v, cited + c, dropped + dr
        if grounded:
            point = grounded[0]
            disposition = Disposition(
                label=d.label if d.label in OUTCOMES else "other",  # type: ignore[arg-type]
                text=point.text,
                pages=point.pages,
                status=point.status,
                quote=point.quote,
            )

    return ContinuationResult(
        document_id=doc_id,
        generated_at=datetime.now(timezone.utc),
        model=llm.name,
        mode=context.mode,  # type: ignore[arg-type]
        pages_in_context=len(context.pages),
        total_pages=len(pages),
        coverage_note=context.note,
        court_level=level,  # type: ignore[arg-type]
        court_level_basis=basis,
        disposition=disposition,
        grounding=Grounding(points_total=total, verified=verified, cited=cited, dropped_unsupported=dropped),
        avenues=avenues_for(level),
        avenues_intro=CONTINUATION_AVENUES_INTRO,
        avenues_notice=CONTINUATION_AVENUES_NOTICE,
        disclaimer=DISCLAIMER_TEXT,
        **sections,
    )
